// ── 토큰 파싱/조인 헬퍼(순수 함수) ─────────────────────────────────────────────
// 콤마 split → trim → 빈 토큰 제거. 중복은 제거하지 않는다(원본 보존 — 중복 처리는 소비 측 책임).
export function parseTokens(value) {
  if (value == null || value === '') return [];
  return String(value)
    .split(',')
    .map((token) => token.trim())
    .filter((token) => token !== '');
}

export function joinTokens(tokens) {
  return tokens.join(', ');
}

